def _backfill_default_roles() -> None:
    """Tenants created before M0.3 get the default roles; their members had full access, so they become Owners.

    The tenant context is set per tenant so the inserts pass row-level security whatever role runs migrations.
    """
    bind = op.get_bind()
    for tenant_id in bind.execute(sa.text("SELECT id FROM tenant")).scalars().all():
        bind.execute(sa.text("SELECT set_config('app.tenant_id', :t, true)"), {"t": str(tenant_id)})
        for default in default_roles():
            role_id = new_id()
            bind.execute(
                sa.text(
                    "INSERT INTO role (id, tenant_id, system_key, name_en, name_ar, description) "
                    "VALUES (:id, :t, :key, :en, :ar, :desc)"
                ),
                {
                    "id": role_id,
                    "t": tenant_id,
                    "key": default.system_key,
                    "en": default.name_en,
                    "ar": default.name_ar,
                    "desc": default.description,
                },
            )
            bind.execute(
                sa.text(
                    "INSERT INTO role_permission (id, tenant_id, role_id, permission_code) VALUES (:id, :t, :r, :c)"
                ),
                [
                    {"id": new_id(), "t": tenant_id, "r": role_id, "c": code}
                    for code in sorted(default.permissions)
                ],
            )
            if default.system_key == OWNER:
                members = bind.execute(
                    sa.text("SELECT id FROM membership WHERE tenant_id = :t"), {"t": tenant_id}
                ).scalars()
                for membership_id in members.all():
                    bind.execute(
                        sa.text(
                            "INSERT INTO role_assignment (id, tenant_id, membership_id, role_id) "
                            "VALUES (:id, :t, :m, :r)"
                        ),
                        {"id": new_id(), "t": tenant_id, "m": membership_id, "r": role_id},
                    )
    bind.execute(sa.text("SELECT set_config('app.tenant_id', '', true)"))


